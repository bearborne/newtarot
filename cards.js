// ───────────────────────────────────────────────────────────────
//  YOUR DECK
//  Each card sits between { and }, followed by a comma.
//
//    name    – the card's title
//    image   – the picture file inside the "cards" folder
//              (leave it as "" to show just the name)
//    court   – true for the Pages, Knights, Queens and Kings: they are
//              only in the deck when "Court cards" is turned on
//    tags    – the card's tags, using the names from tags.js,
//              e.g. ["dawnbringer", "crossroads"]
//    keywords – a few words that sum the card up,
//              e.g. ["beginnings", "trust"]
//    correspondences – astrology, element, number and Kabbalah
//              (Golden Dawn system); leave any of them out to hide it
//    short   – a short description of the card, shown in the card
//              window and on its page
//    reversed – what the card means when it comes out upside down
//    reversedKeywords, reversedQuestions – only on cards whose keywords
//              and questions don't fit both ways; the rest use the
//              same keywords and questions upright and reversed
//    questions – questions the card asks you, one per line
//    details – the longer page, shown under "More about this card".
//              Leave an empty line between paragraphs.
//
//  Text goes between ` backticks ` so it can span several lines.
//
//  Pictures: the original 1909 Rider-Waite-Smith deck, drawn by
//  Pamela Colman Smith (public domain), scans from Wikimedia Commons.
